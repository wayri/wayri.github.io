// Source-only visual preview, not a Jekyll build or SEO-plugin qualification.
const fs = require('node:fs');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const root = path.resolve(__dirname, '..');
const escape = value => String(value).replace(/[&<>"']/g, char => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char]));
const read = file => fs.readFileSync(path.join(root,file),'utf8');

function preview() {
    const data = JSON.parse(read('_data/wayricad.json'));
    const source = read('wayricad.html');
    const frontmatter = source.split('---')[1];
    let body = source.slice(source.indexOf('---',3)+3);
    const tools = data.groups.map(group => `<section class="wayricad-tool-group" aria-labelledby="group-${group.id}"><h3 id="group-${group.id}">${escape(group.title)}</h3><dl>${group.tools.map(tool=>`<div class="wayricad-tool" data-search="${escape(group.title+' '+tool.name+' '+tool.description)}"><dt><a href="https://github.com/wayri/WayriCAD/blob/develop/${tool.guide}">${escape(tool.name)}</a></dt><dd>${escape(tool.description)}</dd></div>`).join('')}</dl></section>`).join('');
    const groupStart = body.indexOf('{% for group in site.data.wayricad.groups %}');
    const groupEnd = body.indexOf('{% endfor %}',body.indexOf('{% endfor %}',groupStart)+1)+12;
    if(groupStart<0 || groupEnd<12) throw new Error('Directory template changed; use Jekyll for preview.');
    body = body.slice(0,groupStart)+tools+body.slice(groupEnd);
    body = body.replace(/{% for question in site.data.wayricad.questions %}[\s\S]*?{% endfor %}/,
        data.questions.map(q=>`<details class="wayricad-question"><summary>${escape(q.title)}</summary><p>${escape(q.answer)}</p></details>`).join(''));
    body = body.replace("{% include software-project-links.html %}",read('_includes/software-project-links.html'));
    let layout = read('_layouts/product.html').replace('{% include site-header.html %}',read('_includes/site-header.html'));
    // The real production tags are generated by jekyll-seo-tag, not this helper.
    const title = frontmatter.match(/^title: "(.*)"/m)[1];
    const description = frontmatter.match(/^description: "(.*)"/m)[1];
    layout = layout.replace('{% seo %}',`<title>${escape(title)} [source preview]</title><meta name="description" content="${escape(description)}">`);
    let html = layout.replace('{{ content }}',body);
    html = html.replace(/{% if [\s\S]*?{% endif %}/g,'');
    html = html.replace(/\?v={{ site.time \| date: '%s' }}/g,'');
    html = html.replace(/{{ '([^']+)' \| relative_url }}/g,(_,url)=>url.startsWith('/assets/') ? pathToFileURL(path.join(root,url.slice(1))).href : 'https://wayri.github.io'+url);
    if(/{[{%]/.test(html)) throw new Error('Unrendered Liquid in source preview; use a real Jekyll build.');
    return html;
}

if (require.main === module) {
    const destination = process.argv[2];
    if (!destination) throw new Error('Usage: node tools/preview-wayricad.cjs <scratch-preview.html>');
    fs.writeFileSync(destination,preview());
    console.log(pathToFileURL(path.resolve(destination)).href);
}
module.exports = {preview};
